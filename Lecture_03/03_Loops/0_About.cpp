/*
LOOPS :- Any work within the code which have to repeat again and again,
    this process is called loop.

TYPES OF LOOPS:-
    1. while :-
        --> whatever condition is given inside the while loop,
            the code will run repeatedly until the condition becomes false.
        --> the condition is checked firstly and then the work is done.
        SYNTAX :-
            while(condition) {
            
            }
    
    2. for :-
        SYNTAX :-
            for(Initialization;condition;updation) {
            
                //work
            }
        CODE :-
            for(int i=1;i<=n;i++) {
             
                cout<<i;
            }
    
    3. do-while :- 
        --> Even if the condition is false, the code will still run once
            because in a do-while loops, the work is done first and then
            the condition is checked.
        SYNTAX :-
            do {

                //work

            } while(condition);

NOTE:- 1. In C++ we can define a variable CamelCase.
for example :- ashishKushwah, totalSum. 
*/
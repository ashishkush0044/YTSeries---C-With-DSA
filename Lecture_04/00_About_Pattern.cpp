/*
Key Concepts for Pattern Printing in C++ :- 
    A. Loops:-
        1. Outer loop → Controls the number of rows.
        2. Inner loop → Controls the number of columns or characters in each row.
    B. Nested Loops:-
        1. Most patterns require loops inside loops.
    C. Types of Patterns:-
        1. Star Patterns (e.g., pyramid, triangle, diamond)
        2. Number Patterns (e.g., sequences, Pascal’s triangle)
        3. Character Patterns (e.g., A-Z shapes)
        4. Mixed Patterns (combination of above)
    D. Spacing & Alignment:-
        1. Use spaces (" ") to align shapes like pyramids or diamonds.
        2. Often requires an extra inner loop for spaces
*/
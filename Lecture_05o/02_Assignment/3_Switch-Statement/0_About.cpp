/*
1. SWITCH STATEMENT :- In C++, a switch statement is a multi-way decision-making
                    control structure that allows you to execute one block of code
                    from multiple possible options, based on the value of a single
                    expression (usually an integer or character).
            It is often used as a cleaner alternative to long if-else-if chains when
            comparing the same variable to different constant values.

    SYNTAX :-
        switch (expression) {
    case constant1:
        // Code to execute if expression == constant1
        break;

    case constant2:
        // Code to execute if expression == constant2
        break;

    // You can have any number of case statements
    default:
        // Code to execute if no case matches
}
*/
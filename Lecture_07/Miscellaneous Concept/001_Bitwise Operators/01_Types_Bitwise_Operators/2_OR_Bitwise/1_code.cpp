#include <iostream>
using namespace std;

int main() {
    int num1, num2;
    cout<<"Enter First Number : ";
    cin>>num1;
    cout<<"Enter Last Number : ";
    cin>>num2;

    cout<<"Bitwise OR Operators "<<num1<<" and "<<num2<<" is : "<<(num1 | num2);
    cout<<endl;

    return 0;
}
/*
3. Bitwise XOR(^) Operator.
*/

#include <iostream>
using namespace std;

int main() {
    int num1, num2;
    cout<<"Enter fist Number : ";
    cin>>num1;
    cout<<"Enter last number : ";
    cin>>num2;

    cout<<"Bitwise XOR Operators "<<num1<<" and "<<num2<<" is : "<<(num1 ^ num2);
    cout<<endl;

    return 0;
}
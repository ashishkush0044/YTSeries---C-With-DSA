/*
4. LEFT SHIFT(<<) OPERATOR :- Shifts bits to the left by a specified
                    number of positions, filling the vacated bits with 0.

        EXAMPLE :- 
            1. num = 4
               num<<1
          Sol.:-
            num=4
              |
            (100) --> (1000)
                        |
                       (8)

            2. num = 10
               num<<2
          Sol.:-
            num=10
              |
           (1010) --> (101000)
                         |
                       (40)

    NOTE :-
        Formula :- 
            ans = a*2(pow b)
*/
/*
2. OPERATOR PRECENDENCE :- Precendence means Priority.

    NOTE :-
        1. Whatever we need to solve or run first, we write it 
           inside parentheses [()].

           ex.:- 5-2*6
           case 1:
             --> (5-2)*6
             --> 3*6
             --> 18
           case 2:
             --> 5-(2*6)
             --> 5-12
             --> -7

        2. If there are operators of the same precedence, they are
           evaluated or executed according to associativity.

           ex.:- ans = 4*5%2  (Left to Right)
                     = 20%2
                     = 0
*/